export function createModel(state) {
  const allPeople = () => [
    ...people.founders,
    ...people.mentors,
    ...people.mentorStartups,
    ...people.browseFounders,
    ...people.browseMentorStartups,
    ...people.roomPartners,
  ];
  const roomTypeForPerson = (person) =>
    person.kind === "Mentor" || person.engagement === "Mentorship"
      ? "mentorship"
      : person.engagement === "Co-Marketing Swap"
        ? "marketing"
        : "beta";
  const peopleForRole = () =>
    state.role === "founder"
      ? [
          ...people.founders.filter((person) => person.id !== "campus"),
          ...people.mentors,
        ]
      : people.mentorStartups;
  const roleName = () =>
    state.role === "founder"
      ? state.accountName || "Maria Santos"
      : state.accountName || "David Park";
  const roleInitials = () =>
    roleName()
      .split(/\s+/)
      .map((part) => part[0])
      .join("")
      .slice(0, 2)
      .toUpperCase();
  const roomMilestones = (type, seeded = false) => {
    const names =
      type === "mentorship"
        ? [
            [
              "goals",
              "Goals defined",
              "Agree on the founder’s priority goals and success measures.",
              false,
            ],
            [
              "session",
              "Session scheduled",
              "Book the first guidance session together.",
              false,
            ],
            [
              "guidance",
              "Guidance delivered",
              "Share practical product guidance and key takeaways.",
              true,
            ],
            [
              "followup",
              "Follow-up actions logged",
              "Capture the agreed next steps and owners.",
              false,
            ],
            [
              "reviewed",
              "Engagement reviewed",
              "Reflect on progress and what comes next.",
              false,
            ],
          ]
        : type === "marketing"
          ? [
              [
                "audience",
                "Audience aligned",
                "Agree on the student audiences each team wants to reach.",
                false,
              ],
              [
                "assets",
                "Campaign assets ready",
                "Prepare newsletter and social campaign materials.",
                false,
              ],
              [
                "launch",
                "Campaign launched",
                "Publish the cross-promotion across both channels.",
                true,
              ],
              [
                "results",
                "Results shared",
                "Compare reach, clicks, and sign-ups together.",
                true,
              ],
              [
                "followup",
                "Next steps agreed",
                "Capture what to repeat in the next campaign.",
                false,
              ],
            ]
          : [
              [
                "scope",
                "Scope defined",
                "Both teams agreed on what success looks like.",
                false,
              ],
              [
                "testers",
                "Testers assigned",
                "Invite the agreed group of users to the beta.",
                false,
              ],
              [
                "testing",
                "Testing round",
                "Two-week product testing window.",
                true,
              ],
              [
                "feedback",
                "Feedback submitted",
                "Collect feedback in the shared form.",
                true,
              ],
              [
                "issues",
                "Issues reviewed",
                "Review findings and agree on next steps.",
                false,
              ],
            ];
    return Object.fromEntries(
      names.map(([id, title, description, evidence], index) => [
        id,
        {
          title,
          description,
          evidence,
          me: seeded && index < 2,
          partner: seeded && index < 2,
          attachment: "",
          disputed: false,
          evidenceOpen: false,
          schedule: "",
        },
      ]),
    );
  };
  const senderForRole = (role) => {
    const name =
      role === state.role
        ? roleName()
        : role === "founder"
          ? "Maria Santos"
          : "David Park";
    return {
      name,
      initials: name
        .split(/\s+/)
        .map((part) => part[0])
        .join("")
        .slice(0, 2)
        .toUpperCase(),
    };
  };
  const createRoom = ({
    id,
    role,
    partnerId,
    type,
    status = "matched",
    seeded = false,
    sender,
  }) => {
    const partner = allPeople().find((person) => person.id === partnerId);
    const roomSender = sender || senderForRole(role);
    const terms =
      type === "mentorship"
        ? {
            goal: `Monthly product sessions with ${partner ? partner.name : "startup"}`,
            scope:
              "Hold monthly mentoring sessions, review onboarding progress, and agree practical next steps.",
            timeline: "3 months",
            commitment: "One 60-minute session per month with async follow-up",
            compensation: "No cash payment; mentorship and practical feedback",
          }
        : type === "marketing"
          ? {
              goal: `Coordinate a co-marketing campaign with ${partner ? partner.name : "your partner"}`,
              scope:
                "Coordinate a newsletter feature and social campaign to introduce each team’s product to aligned student audiences.",
              timeline: "1 month",
              commitment:
                "One planning call, shared campaign assets, and a results review",
              compensation: "Reciprocal promotion across both communities",
            }
          : {
              goal: `Run a focused beta-testing exchange with ${partner ? partner.name : "your partner"}`,
              scope:
                "Invite a focused group of users to the beta and collect feedback through a shared form.",
              timeline: "2 weeks",
              commitment: "One kickoff, weekly check-ins, and a final review",
              compensation:
                "No cash payment; both teams share feedback and learning",
            };
    return {
      id,
      role,
      type,
      partnerId,
      engagementType:
        partner?.engagement ||
        (type === "mentorship" ? "Mentorship" : "Beta Testing Exchange"),
      status,
      terms: {
        draft: terms,
        locked: seeded,
        partnerLocked: seeded,
      },
      milestones: roomMilestones(type, seeded),
      messages: [
        {
          who: "partner",
          name: partner ? partner.name : "Partner",
          initials: partner ? partner.initials : "?",
          text:
            type === "mentorship"
              ? "Let’s agree on your priority goals and schedule our first session."
              : type === "marketing"
                ? "Let’s coordinate the campaign and agree which channels to feature."
                : "Let’s agree on the test flow and next steps together.",
          time: "Just now",
        },
        {
          who: "me",
          name: roomSender.name,
          initials: roomSender.initials,
          text: "Sounds good. I’ll add a first draft of our goals and timeline here.",
          time: "Just now",
        },
      ],
      targetDate: "Nov 30, 2026",
      review: {
        me: false,
        partner: false,
      },
      progress: seeded ? 40 : 0,
    };
  };
  function currentAgreement() {
    return activeRoom().terms;
  }
  const activeRoom = () =>
    state.rooms[state.activeRoomId] ||
    state.rooms[
      state.role === "founder" ? "founder-campus" : "mentor-budgetbuddy"
    ];
  const roomStatusLabel = (status, partnerName) =>
    status === "terms"
      ? `Waiting for ${partnerName || "your partner"} to confirm`
      : {
          matched: "Matched",
          "in-progress": "In progress",
          launched: "Launched",
          reviewed: "Reviewed",
        }[status];
  const matches = () =>
    [...peopleForRole()].sort((first, second) => second.score - first.score);
  const browsePeople = () =>
    state.role === "founder"
      ? [...peopleForRole(), ...people.browseFounders]
      : [...peopleForRole(), ...people.browseMentorStartups];
  const rolePeople = () => [
    ...new Map(
      [...matches(), ...browsePeople()].map((person) => [person.id, person]),
    ).values(),
  ];
  const savedMatches = () => state.savedByRole[state.role];
  const waitingMatches = () => state.waitingByRole[state.role];
  const interestedMatches = () => state.interestByRole[state.role];
  const scoreFactors = (person) => {
    const factors = [
      ["Need Fit", 0],
      ["Expertise Fit", 1],
      ["Industry Fit", 2],
      ["Stage/Size Fit", 3],
      ["Goal Fit", 4],
    ];
    return person.kind === "Mentor" || state.role === "mentor"
      ? factors
      : factors.filter(([, index]) => index !== 1);
  };
  const roleLabel = () =>
    state.role === "founder" ? "Startup founder" : "Mentor";
  const statusText = (id) => {
    const item = activeRoom().milestones[id];
    if (item.me && item.partner) return "Confirmed by both";
    if (item.me || item.partner) return "Waiting on partner";
    return "Needs confirmation";
  };
  const existingRoomFor = (role, partnerId) =>
    Object.values(state.rooms).find(
      (room) => room.role === role && room.partnerId === partnerId,
    );
  return {
    state,
    people,
    allPeople,
    roomTypeForPerson,
    peopleForRole,
    roleName,
    roleInitials,
    roomMilestones,
    senderForRole,
    createRoom,
    currentAgreement,
    activeRoom,
    roomStatusLabel,
    matches,
    browsePeople,
    rolePeople,
    savedMatches,
    waitingMatches,
    interestedMatches,
    scoreFactors,
    roleLabel,
    statusText,
    existingRoomFor,
  };
}
